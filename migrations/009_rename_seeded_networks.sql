-- v0.2.10：种子网络改名。
--
-- 008 把 Agent 网段网络的名字写成 '网络 ' || subnet（如 '网络 192.168.1.0/24'），
-- 前端在名字前又加"网络"标签、后面又并列网段，导致设备页显示
-- "网络 网络 192.168.1.0/24 / 网段 192.168.1.0/24" 三重重复。
-- 本迁移只改 008 自动种子的行（name = '网络 ' || cidr），改名后名字
-- 即 CIDR 本身（如 '192.168.1.0/24'）；用户手工改过名的网络与默认网络
-- 一律不动。008 是已发布的迁移，本文件只做增量修正，绝不改 008。
-- 幂等：重复执行不改变任何行。
UPDATE networks SET name = cidr
WHERE id LIKE 'net-%' AND cidr <> '' AND name = '网络 ' || cidr;
